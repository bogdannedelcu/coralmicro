#!/usr/bin/env python3
"""Generate the SentAI A4 takeoff/landing pad — 4× ArUco 4x4_50 markers
at the exact positions used in sentai_crazysim.sdf + mission_s158.py.

Output:
  s158_calib_takeoff/a4_takeoff_pad.png   (300 DPI, 2480×3508 px)
  s158_calib_takeoff/a4_takeoff_pad.pdf   (vector-clean print)

Run: python3 examples/sentai_runtime/experiments/s158_calib_takeoff/generate_a4_pad.py
"""
from __future__ import annotations

from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

# ─── Geometry (METRIC, must match sentai_crazysim.sdf + mission_s158.py) ─
A4_W_MM       = 210.0
A4_H_MM       = 297.0
DPI           = 300
MARKER_SIDE_M = 0.06              # 60 mm
MARKER_W_M = {
    0: (+0.06, +0.10),            # top-right (+x, +y world)
    1: (-0.06, +0.10),            # top-left
    2: (-0.06, -0.10),            # bottom-left
    3: (+0.06, -0.10),            # bottom-right
}

# Texture source (real OpenCV 4x4_50 markers, same PNGs Gazebo loads).
SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT  = SCRIPT_DIR.parents[3]
TEXTURE_DIR = REPO_ROOT / "sim" / "gazebo" / "materials" / "textures"


def mm_to_px(mm: float) -> int:
    return int(round(mm * DPI / 25.4))


def world_to_page_px(x_m: float, y_m: float):
    """World frame: +x right, +y forward.  Page (PIL image): origin
    top-left, +x right, +y DOWN.  The A4 page is oriented portrait —
    top of page = +y world."""
    cx = mm_to_px(A4_W_MM / 2.0)
    cy = mm_to_px(A4_H_MM / 2.0)
    return (cx + mm_to_px(x_m * 1000.0),
            cy - mm_to_px(y_m * 1000.0))


def main() -> int:
    out_png = SCRIPT_DIR / "a4_takeoff_pad.png"
    out_pdf = SCRIPT_DIR / "a4_takeoff_pad.pdf"
    W, H = mm_to_px(A4_W_MM), mm_to_px(A4_H_MM)
    img = Image.new("RGB", (W, H), color=(255, 255, 255))
    draw = ImageDraw.Draw(img)

    side_px = mm_to_px(MARKER_SIDE_M * 1000.0)
    for mid, (x, y) in MARKER_W_M.items():
        png = TEXTURE_DIR / f"aruco_4x4_50_id{mid}.png"
        marker = Image.open(png).convert("RGB")
        marker_resized = marker.resize((side_px, side_px), Image.NEAREST)
        cx_px, cy_px = world_to_page_px(x, y)
        tl = (cx_px - side_px // 2, cy_px - side_px // 2)
        img.paste(marker_resized, tl)

    # Crosshair at page centre + axis labels.
    cx, cy = mm_to_px(A4_W_MM / 2), mm_to_px(A4_H_MM / 2)
    CROSS = mm_to_px(8.0)
    draw.line([(cx - CROSS, cy), (cx + CROSS, cy)], fill=(180, 180, 180), width=3)
    draw.line([(cx, cy - CROSS), (cx, cy + CROSS)], fill=(180, 180, 180), width=3)
    # +y axis arrow toward top.
    arrow_len = mm_to_px(20.0)
    draw.line([(cx, cy - mm_to_px(5)), (cx, cy - arrow_len)],
              fill=(40, 100, 200), width=4)
    draw.polygon([(cx - 8, cy - arrow_len + 8),
                  (cx + 8, cy - arrow_len + 8),
                  (cx,     cy - arrow_len - 6)], fill=(40, 100, 200))
    # +x axis arrow toward right.
    draw.line([(cx + mm_to_px(5), cy), (cx + arrow_len, cy)],
              fill=(200, 60, 60), width=4)
    draw.polygon([(cx + arrow_len - 8, cy - 8),
                  (cx + arrow_len - 8, cy + 8),
                  (cx + arrow_len + 6, cy)], fill=(200, 60, 60))

    # Text annotations.
    try:
        font_large = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/"
                                          "DejaVuSans-Bold.ttf",
                                          size=mm_to_px(5))
        font_small = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/"
                                          "DejaVuSans.ttf",
                                          size=mm_to_px(3.5))
    except OSError:
        font_large = ImageFont.load_default()
        font_small = ImageFont.load_default()

    draw.text((mm_to_px(8), mm_to_px(8)),
              "SentAI takeoff/landing pad — A4 portrait",
              fill=(0, 0, 0), font=font_large)
    spec_lines = [
        "ArUco 4×4_50 dict, ids 0/1/2/3, 60×60 mm each",
        "Marker centres at (±60, ±100) mm from page centre",
        "World frame: +x = right (red), +y = forward (blue)",
        "Print at 100% scale, NO 'fit to page' — verify markers exactly 60 mm",
        "Lay flat on rigid surface (cardboard backing).  Drone hover z = 0.5-0.6 m.",
        f"Generated by examples/sentai_runtime/experiments/s158_calib_takeoff/",
    ]
    y0 = mm_to_px(A4_H_MM - 25)
    for i, line in enumerate(spec_lines):
        draw.text((mm_to_px(8), y0 + i * mm_to_px(3.5)),
                  line, fill=(0, 0, 0), font=font_small)

    img.save(out_png, dpi=(DPI, DPI))
    img.save(out_pdf, "PDF", resolution=float(DPI))
    print(f"wrote {out_png}")
    print(f"wrote {out_pdf}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
